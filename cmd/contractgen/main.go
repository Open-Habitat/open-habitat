package main

import (
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"
)

func main() {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "fail on generated drift")
	flag.Parse()
	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(root string, check bool) error {
	files, err := filepath.Glob(filepath.Join(root, "contracts/v1/*.schema.json"))
	if err != nil {
		return err
	}
	if len(files) == 0 {
		return fmt.Errorf("no canonical schemas found below %s", filepath.Join(root, "contracts/v1"))
	}
	sort.Strings(files)
	hash := sha256.New()
	names := make([]string, 0, len(files))
	families := make([]string, 0, len(files))
	for _, path := range files {
		body, readErr := os.ReadFile(path)
		if readErr != nil {
			return readErr
		}
		name := filepath.Base(path)
		hash.Write([]byte(name))
		hash.Write([]byte{0})
		hash.Write(body)
		names = append(names, name)
		families = append(families, familyName(name))
	}
	fingerprint := hex.EncodeToString(hash.Sum(nil))
	goOut := []byte("// Code generated by contractgen; DO NOT EDIT.\npackage contracts\n\nimport \"encoding/json\"\n\nconst V1SchemaFingerprint = \"" + fingerprint + "\"\n\nvar V1SchemaFiles = []string{\n")
	for _, name := range names {
		goOut = append(goOut, []byte(fmt.Sprintf("\t%q,\n", name))...)
	}
	goOut = append(goOut, []byte("}\n\n// Wire families remain opaque until validated against their canonical JSON Schema.\n")...)
	for _, family := range families {
		goOut = append(goOut, []byte(fmt.Sprintf("type %s = json.RawMessage\n", family))...)
	}
	tsOut := []byte(fmt.Sprintf("// Code generated by contractgen; DO NOT EDIT.\nexport const contractSchemaVersion = 1 as const;\nexport const v1SchemaFingerprint =\n  %q as const;\n\n// Wire families remain unknown until validated at the HTTP/SSE boundary.\n", fingerprint))
	for _, family := range families {
		tsOut = append(tsOut, []byte(fmt.Sprintf("export type %s = unknown;\n", family))...)
	}
	outputs := map[string][]byte{
		filepath.Join(root, "internal/contracts/v1_gen.go"):      goOut,
		filepath.Join(root, "web/src/contracts/v1.generated.ts"): tsOut,
	}
	for path, wanted := range outputs {
		got, readErr := os.ReadFile(path)
		if check {
			if readErr != nil || string(got) != string(wanted) {
				return fmt.Errorf("generated contract drift: %s (run go generate ./internal/contracts)", path)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, wanted, 0o644); err != nil {
			return err
		}
	}
	fmt.Printf("contract generation %s (%s)\n", map[bool]string{true: "clean", false: "complete"}[check], strings.Join(names, ", "))
	return nil
}

func familyName(schemaFile string) string {
	base := strings.TrimSuffix(schemaFile, ".schema.json")
	var result []rune
	upper := true
	for _, character := range base {
		if character == '-' || character == '_' {
			upper = true
			continue
		}
		if upper {
			character = unicode.ToUpper(character)
			upper = false
		}
		result = append(result, character)
	}
	return string(result)
}
