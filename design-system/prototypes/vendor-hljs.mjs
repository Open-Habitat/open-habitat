#!/usr/bin/env node
// Bundles highlight.js core with the languages production registers
// (web/src/components/SyntaxCode.tsx) into lib/vendor/hljs.js, a global `hljs`.
// Rerun when production's language list or highlight.js version changes:
//   node vendor-hljs.mjs
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '../../web');
const src = readFileSync(join(web, 'src/components/SyntaxCode.tsx'), 'utf8');
const langs = [...src.matchAll(/^\s*(\w+): \(\) => import\("highlight\.js\/lib\/languages\/(\w+)"\)/gm)].map(m => [m[1], m[2]]);
const entry = `import hljs from 'highlight.js/lib/core';\n${langs.map(([k, f]) => `import ${k} from 'highlight.js/lib/languages/${f}';\nhljs.registerLanguage('${k}', ${k});`).join('\n')}\nhljs.registerAliases(['shell', 'sh', 'zsh'], { languageName: 'bash' });\nwindow.hljs = hljs;\n`;
const version = JSON.parse(readFileSync(join(web, 'node_modules/highlight.js/package.json'), 'utf8')).version;
const out = execFileSync(join(web, 'node_modules/.bin/esbuild'), ['--bundle', '--minify', '--format=iife', '--loader=js'], { input: entry, cwd: web });
writeFileSync(join(here, 'lib/vendor/hljs.js'), `// highlight.js ${version} (BSD-3-Clause), core + ${langs.map(l => l[0]).join(', ')}. Generated by vendor-hljs.mjs.\n${out}`);
console.log(`lib/vendor/hljs.js: highlight.js ${version}, ${langs.length} languages, ${out.length} bytes`);
