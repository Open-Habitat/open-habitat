#!/usr/bin/env bash
# One declared unit owns all preparation and checks; never invokes another queue slot.
set -euo pipefail
cd "$(dirname "$0")/.."
area=${1:?area required};shift
umask 077
# Admission is verified before executing heavy commands, even when invoked directly.
where=$(python3 scripts/browser-focused.py --placement)
if [[ $where == remote ]];then echo 'error: runner-area must execute inside its declared job, not Alder' >&2;exit 2;fi
case "$area" in
  web) npm ci --prefix web --ignore-scripts --no-audit --no-fund; exec bash scripts/test-web-fast.sh;;
  go|go-contracts)
    npm ci --prefix internal/daemon/pi-device-test --ignore-scripts --no-audit --no-fund
    go vet "${@:-./...}"
    go test -race -count=1 "${@:-./...}"
    if [[ $area == go ]];then exit;fi
    ;;
  contracts) ;;
  *) echo 'error: unknown area' >&2;exit 2;;
esac
# Check committed generated bytes before regeneration: otherwise a dirty-source
# task could quietly repair drift and falsely report it passed.
bash scripts/check-generated.sh
go generate ./internal/contracts
bash scripts/check-generated.sh
venv=$(mktemp -d /var/tmp/oh-contracts.XXXXXX)
trap 'rm -rf "$venv"' EXIT
python3 -m venv "$venv"
"$venv/bin/pip" install --disable-pip-version-check --no-input -r requirements-ci.txt
"$venv/bin/python" scripts/validate-contracts.py
