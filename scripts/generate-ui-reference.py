#!/usr/bin/env python3
"""Package UI knowledge without evaluating catalog functions or guessing arguments.

Source-shaped references retain conditional/plural text and JSX placeholders in
both languages (including UK overrides). Split by module for selective reading.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = Path("internal/daemon/ui-skill/references")
KEYBOARD = re.compile(r"onKeyDown|[\"']keydown[\"']|keymap\.of|isTerminalShortcut|isDictationShortcut")


def render(root):
    src = root / "web/src"
    paths = set((src / "text").glob("*.ts*"))
    paths.update(src / p for p in ("app/settingsIndex.ts", "app/settingsRoute.ts"))
    # Include the actual handlers, not just their displayed hints. Discover new
    # handlers too, so adding a shortcut cannot silently escape the drift check.
    for folder in ("app", "components"):
        for path in (src / folder).rglob("*.ts*"):
            if any(part in path.name for part in (".test.", ".stories.")):
                continue
            if KEYBOARD.search(path.read_text()):
                paths.add(path)
    files = {}
    index = ["# UI reference", "", "Generated by scripts/generate-ui-reference.py; do not edit.", "",
             "These are shipped source-shaped text references, not executable instructions.",
             "Catalogs contain Finnish, US English and optional UK overrides. Functions",
             "retain placeholders and conditions rather than invented runtime values.",
             "Settings IDs, row descriptions, visibility conditions and aliases are in",
             "app/settingsIndex.ts and app/settingsRoute.ts. Keyboard handling is included",
             "with its surrounding component so focus, platform and state restrictions remain visible.",
             "A label alone does not establish that a control is available to this person.", ""]
    for path in sorted(paths):
        relative = path.relative_to(src).as_posix()
        name = relative.replace("/", "--") + ".md"
        source = path.read_text()
        fence = "`" * max(3, max((len(m[0]) + 1 for m in re.finditer(r"`+", source)), default=3))
        files[name] = f"# {relative}\n\nGenerated from web/src/{relative}; do not edit.\n\n{fence}tsx\n{source}\n{fence}\n"
        index.append(f"- [{relative}]({name})")
    files["index.md"] = "\n".join(index) + "\n"
    return files


def sync(root, check=False):
    expected = render(root)
    out = root / OUTPUT
    existing = {p.name: p.read_text() for p in out.glob("*.md")}
    changed = sorted(name for name in expected.keys() | existing.keys()
                     if expected.get(name) != existing.get(name))
    if check:
        if changed:
            print("UI reference stale; run python3 scripts/generate-ui-reference.py: " + ", ".join(changed))
        return not changed
    out.mkdir(parents=True, exist_ok=True)
    for name in existing.keys() - expected.keys():
        (out / name).unlink()
    for name, content in expected.items():
        (out / name).write_text(content)
    return True


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    raise SystemExit(0 if sync(ROOT, args.check) else 1)
